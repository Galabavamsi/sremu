def max_rel(a: ArrayLike, b: ArrayLike) -> float:
    """``max |a - b| / |b|`` element-wise (b is the reference)."""
    av = np.asarray(a)
    bv = np.asarray(b)
    return float(np.max(np.abs(av - bv) / np.abs(bv)))


def max_rel_floor(a: ArrayLike, b: ArrayLike, floor: ArrayLike) -> float:
    """``max |a - b| / max(|b|, floor)``: relative error with a per-element magnitude floor.

    Used where the reference can be exactly 0 (e.g. a LOS path in the back lobe of a
    CosPower antenna): ``floor`` is the isotropic magnitude of the same path, so the error is
    relative to what the path would carry without the pattern null.
    """
    av = np.asarray(a)
    bv = np.asarray(b)
    den = np.maximum(np.abs(bv), np.asarray(floor, dtype=float))
    return float(np.max(np.abs(av - bv) / den))


def max_rel_to_peak(a: ArrayLike, b: ArrayLike) -> float:
    """``max |a - b| / max |b|``: relative error for patterns that pass through nulls."""
    av = np.asarray(a)
    bv = np.asarray(b)
    return float(np.max(np.abs(av - bv)) / np.max(np.abs(bv)))


def parabolic_peak(x: ArrayLike, y_db: ArrayLike, mask: ArrayLike) -> tuple[float, float]:
    """Peak of a uniformly sampled dB curve inside ``mask`` by parabolic interpolation.

    Same rule as ``parabolic_peak`` in ``golden_beam_pattern.m``.
    """
    xv = np.asarray(x, dtype=float)
    yv = np.asarray(y_db, dtype=float)
    idx = np.flatnonzero(np.asarray(mask))
    i = int(idx[np.argmax(yv[idx])])
    a, b, c = yv[i - 1], yv[i], yv[i + 1]
    d = 0.5 * (a - c) / (a - 2 * b + c)
    return float(xv[i] + d * (xv[1] - xv[0])), float(b - 0.25 * (a - c) * d)


def level_errors_db(
    h_test_db: ArrayLike, h_ref_db: ArrayLike, floor_db: float = 30.0
) -> NDArray[np.float64]:
    """Level differences where the reference is within ``floor_db`` of its peak (G2 rule)."""
    t = np.asarray(h_test_db, dtype=float)
    r = np.asarray(h_ref_db, dtype=float)
    keep = r >= r.max() - floor_db
    return t[keep] - r[keep]


@dataclass(frozen=True)
class FadingStats:
    """ST-02 statistics of a complex fading series (unit mean power after normalization)."""

    lags_s: NDArray[np.float64]
    acf: NDArray[np.float64]
    lcr_m10db_hz: float
    ks_envelope: float


def fading_stats(
    g: ArrayLike,
    f_s: float,
    max_lag_s: float = 0.1,
    cdf: Callable[[NDArray], NDArray] | None = None,
) -> FadingStats:
    """ACF (unbiased, mean removed, normalized to lag 0), LCR at -10 dB and envelope KS.

    Mirrors ``golden_fading_sos.m``: the series is normalized to unit mean power; LCR counts
    downward crossings of 10^(-10/20) per second; KS against ``cdf`` (Rayleigh by default).
    """
    gv = np.asarray(g, dtype=complex)
    gn = gv / math.sqrt(float(np.mean(np.abs(gv) ** 2)))
    n = gn.size
    max_lag = round(max_lag_s * f_s)
    gd = gn - gn.mean()
    nfft = 1 << math.ceil(math.log2(2 * n))
    spec = np.fft.fft(gd, nfft)
    r = np.fft.ifft(np.abs(spec) ** 2)[: max_lag + 1] / (n - np.arange(max_lag + 1))
    acf = np.real(r / r[0])
    env = np.abs(gn)
    below = env < 10 ** (-10 / 20)
    lcr = float(np.sum(~below[:-1] & below[1:])) / (n / f_s)
    if cdf is None:

        def cdf(x: NDArray) -> NDArray:
            return 1.0 - np.exp(-x * x)

    xs = np.sort(env)
    f = cdf(xs)
    i = np.arange(1, n + 1)
    ks = float(max(np.max(i / n - f), np.max(f - (i - 1) / n)))
    return FadingStats(np.arange(max_lag + 1) / f_s, acf, lcr, ks)
