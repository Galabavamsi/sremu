def sha256_lf(path: Path) -> str:
    """sha256 of a text file with CRLF normalized to LF (as ``golden_util_sha256.m``)."""
    return hashlib.sha256(path.read_bytes().replace(b"\r\n", b"\n")).hexdigest()


@cache
def load_meta(golden_id: str) -> dict[str, Any]:
    """The ``<golden_id>.meta.json`` written by ``golden_util_write_meta.m``."""
    return json.loads((GOLDEN_DIR / f"{golden_id}.meta.json").read_text(encoding="utf-8"))


@cache
def _load_csv(name: str) -> tuple[tuple[str, ...], tuple[tuple[str, ...], ...]]:
    with (GOLDEN_DIR / name).open(newline="", encoding="ascii") as f:
        rows = list(csv.reader(f))
    return tuple(rows[0]), tuple(tuple(r) for r in rows[1:])


def load_csv(name: str) -> dict[str, NDArray]:
    """Columns of a golden CSV: float64 arrays, or str arrays for non-numeric columns."""
    header, rows = _load_csv(name)
    out: dict[str, NDArray] = {}
    for j, col in enumerate(header):
        vals = [r[j] for r in rows]
        try:
            out[col] = np.array([float(v) for v in vals], dtype=np.float64)
        except ValueError:
            out[col] = np.array(vals, dtype=str)
    return out


def complex_col(cols: dict[str, NDArray], stem: str) -> NDArray[np.complex128]:
    """``<stem>_re + 1j*<stem>_im`` from a loaded golden CSV."""
    return cols[f"{stem}_re"] + 1j * cols[f"{stem}_im"]


def integrity_errors(golden_id: str) -> list[str]:
    """Problems with a golden's provenance (empty when everything matches)."""
    meta = load_meta(golden_id)
    errs: list[str] = []
    if meta.get("matlab_release") != "2026a" or "R2026a" not in meta.get("matlab_version", ""):
        errs.append(f"{golden_id}: not generated by MATLAB R2026a ({meta.get('matlab_version')})")
    if meta.get("data_class") != "MATLAB":
        errs.append(f"{golden_id}: data_class {meta.get('data_class')!r} != 'MATLAB'")
    script = MATLAB_DIR / meta["script"]
    if not script.is_file():
        errs.append(f"{golden_id}: generating script {script} missing")
    elif sha256_lf(script) != meta["script_sha256"]:
        errs.append(
            f"{golden_id}: {meta['script']} changed since the golden was generated;"
            " rerun run_goldens.ps1"
        )
    for key, sha in meta.get("helpers_sha256", {}).items():
        helper = MATLAB_DIR / (key[:-2] + ".m" if key.endswith("_m") else key)
        if not helper.is_file() or sha256_lf(helper) != sha:
            errs.append(
                f"{golden_id}: helper {helper.name} missing or changed; rerun run_goldens.ps1"
            )
    outputs = meta["outputs"] if isinstance(meta["outputs"], list) else [meta["outputs"]]
    for o in outputs:
        f = GOLDEN_DIR / o["file"]
        if not f.is_file():
            errs.append(f"{golden_id}: output {o['file']} missing")
            continue
        if sha256_lf(f) != o["sha256"]:
            errs.append(f"{golden_id}: output {o['file']} sha256 differs from its meta")
        if len(_load_csv(o["file"])[1]) != int(o["rows"]):
            errs.append(f"{golden_id}: output {o['file']} row count differs from its meta")
    if not (isinstance(meta.get("runtime_s"), int | float) and meta["runtime_s"] > 0):
        errs.append(f"{golden_id}: runtime_s missing")
    return errs


