"""Generate docs/model_card.md and paper Table II from docs/model_card.yaml (WP12).

docs/model_card.yaml is the single source of the physics model card (DESIGN 5, 5.15).
This script renders
  * docs/model_card.md                      (always; --check verifies it is up to date)
  * a LaTeX table* for the paper            (--tex PATH; ASCII-only, IEEEtran-ready)

Standard library + PyYAML. No sremu import, so the paper pipeline can call it with any
Python that has PyYAML.

Usage:
  python docs/tools/gen_model_card.py [--yaml F] [--md F] [--tex F] [--check]
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path
from typing import Any

import yaml

DOCS = Path(__file__).resolve().parents[1]
REQUIRED = ("id", "component", "model", "validity_domain", "evidence", "default")
ID_RE = re.compile(
    r"^(PH-\d{2}|ST-\d{2}|RT-\d{2}|IO-\d{2}|G[1-8]|W[1-6]|V-(?:TANG|LAB|CFO|WCL|FM)(?:-\d)?)$"
)
UNICODE_TEX = {
    "λ": r"$\lambda$",
    "≥": r"$\geq$",
    "≤": r"$\leq$",
    "ε": r"$\varepsilon$",
    "ν": r"$\nu$",
    "Γ": r"$\Gamma$",
    "−": r"$-$",
    "—": "---",
    "–": "--",
    "§": r"\S{}",
    ">": r"$>$",
    "<": r"$<$",
}
TEX_SPECIALS = {
    "\\": r"\textbackslash{}",
    "&": r"\&",
    "%": r"\%",
    "$": r"\$",
    "#": r"\#",
    "_": r"\_",
    "{": r"\{",
    "}": r"\}",
    "~": r"\textasciitilde{}",
    "^": r"\textasciicircum{}",
}


class ModelCardError(ValueError):
    pass


def load(path: Path) -> dict[str, Any]:
    with path.open(encoding="utf-8") as fh:
        doc = yaml.safe_load(fh)
    validate(doc)
    return doc


def validate(doc: dict[str, Any]) -> None:
    if doc.get("schema_version") != 1:
        raise ModelCardError("schema_version must be 1")
    rows = doc.get("rows")
    if not isinstance(rows, list) or not rows:
        raise ModelCardError("rows must be a non-empty list")
    seen: set[str] = set()
    for r in rows:
        for k in REQUIRED:
            if k not in r:
                raise ModelCardError(f"row {r.get('id')!r}: missing {k!r}")
        for k in ("component", "model", "validity_domain", "default"):
            if not isinstance(r[k], str):  # catches YAML 1.1 booleans such as unquoted On/Off
                raise ModelCardError(f"row {r['id']!r}: {k!r} must be a string, got {r[k]!r}")
        if r["id"] in seen:
            raise ModelCardError(f"duplicate row id {r['id']!r}")
        seen.add(r["id"])
        ev = r["evidence"]
        if not isinstance(ev, list) or not ev:
            raise ModelCardError(f"row {r['id']!r}: evidence must be a non-empty list")
        for e in ev:
            if not ID_RE.match(str(e)):
                raise ModelCardError(f"row {r['id']!r}: {e!r} is not a spec test id")


# --------------------------------------------------------------------------- LaTeX
def tex_escape(text: str) -> str:
    """Plain cell text -> ASCII LaTeX (backtick spans become \\texttt)."""
    parts = re.split(r"(`[^`]*`)", text)
    out = []
    for part in parts:
        code = part.startswith("`") and part.endswith("`") and len(part) >= 2
        body = part[1:-1] if code else part
        s = "".join(TEX_SPECIALS.get(ch, ch) for ch in body)
        s = "".join(UNICODE_TEX.get(ch, ch) for ch in s)
        out.append(rf"\texttt{{{s}}}" if code else s)
    res = "".join(out)
    bad = sorted({ch for ch in res if ord(ch) > 127})
    if bad:
        raise ModelCardError(f"no LaTeX mapping for {bad} in {text!r}")
    return res


def compress_ids(ids: list[str]) -> list[str]:
    """['PH-02','PH-03','PH-04'] -> ['PH-02--04']; other ids unchanged."""
    out: list[str] = []
    i = 0
    while i < len(ids):
        m = re.fullmatch(r"([A-Z]+-?)(\d+)", ids[i])
        j = i
        if m:
            prefix, width = m.group(1), len(m.group(2))
            while j + 1 < len(ids):
                n = re.fullmatch(re.escape(prefix) + r"(\d+)", ids[j + 1])
                if not n or int(n.group(1)) != int(m.group(2)) + (j + 1 - i):
                    break
                j += 1
            if j - i >= 2:
                last = re.fullmatch(re.escape(prefix) + r"(\d+)", ids[j])
                assert last is not None
                out.append(f"{ids[i]}--{last.group(1).zfill(width)}")
                i = j + 1
                continue
        out.append(ids[i])
        i += 1
    return out


def cell(row: dict[str, Any], key: str) -> str:
    return str(row[f"{key}_tex"]) if f"{key}_tex" in row else tex_escape(row[key])


def render_tex(doc: dict[str, Any]) -> str:
    lines = [
        "% GENERATED by sremu/docs/tools/gen_model_card.py from docs/model_card.yaml.",
        "% Do not edit; edit the YAML and rerun the paper pipeline.",
        r"\begin{table*}[t]",
        r"\caption{" + tex_escape(" ".join(str(doc["caption"]).split())) + "}",
        r"\label{tab:modelcard}",
        r"\centering",
        r"\footnotesize",
        r"\setlength{\tabcolsep}{3pt}",
        r"\begin{tabular}{@{}>{\raggedright\arraybackslash}p{0.95in}"
        r">{\raggedright\arraybackslash}p{1.65in}>{\raggedright\arraybackslash}p{2.25in}"
        r">{\raggedright\arraybackslash}p{1.35in}>{\raggedright\arraybackslash}p{0.6in}@{}}",
        r"\toprule",
        r"Component & Model & Validity domain & Evidence & Default \\",
        r"\midrule",
    ]
    for r in doc["rows"]:
        ev = ", ".join(rf"\texttt{{{e}}}" for e in compress_ids([str(x) for x in r["evidence"]]))
        lines.append(
            f"{cell(r, 'component')} & {cell(r, 'model')} & {cell(r, 'validity_domain')} & "
            f"{ev} & {cell(r, 'default')} \\\\"
        )
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table*}"]
    text = "\n".join(lines) + "\n"
    bad = sorted({ch for ch in text if ord(ch) > 127})
    if bad:
        raise ModelCardError(f"non-ASCII characters in LaTeX output: {bad}")
    return text


# --------------------------------------------------------------------------- Markdown
def render_md(doc: dict[str, Any]) -> str:
    def md(s: str) -> str:
        return s.replace("|", "\\|")

    out = [
        "<!-- GENERATED by docs/tools/gen_model_card.py from docs/model_card.yaml;"
        " do not edit. -->",
        "",
        f"# {doc['title']}",
        "",
        " ".join(str(doc["caption"]).split()),
        "",
        f"Source of truth: `docs/model_card.yaml` ({doc['spec']}).",
        "",
        "| Component | Model | Validity domain | Evidence | Default | Spec | Status |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in doc["rows"]:
        ev = ", ".join(compress_ids([str(x) for x in r["evidence"]])).replace("--", "–")
        out.append(
            f"| {md(r['component'])} | {md(r['model'])} | {md(r['validity_domain'])} | {ev} | "
            f"{md(r['default'])} | §{r.get('spec_section', '')} | {r.get('status', '')} |"
        )
    return "\n".join(out) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--yaml", type=Path, default=DOCS / "model_card.yaml")
    ap.add_argument("--md", type=Path, default=DOCS / "model_card.md")
    ap.add_argument("--tex", type=Path, default=None, help="also write the LaTeX table here")
    ap.add_argument("--check", action="store_true", help="fail if the Markdown is out of date")
    args = ap.parse_args(argv)
    try:
        doc = load(args.yaml)
        md_text = render_md(doc)
        tex_text = render_tex(doc) if args.tex else None
    except ModelCardError as exc:
        print(f"model card error: {exc}", file=sys.stderr)
        return 2
    if args.check:
        current = args.md.read_text(encoding="utf-8") if args.md.is_file() else ""
        if current != md_text:
            print(f"{args.md} is out of date; rerun gen_model_card.py", file=sys.stderr)
            return 1
        return 0
    args.md.write_text(md_text, encoding="utf-8", newline="\n")
    if tex_text is not None:
        args.tex.parent.mkdir(parents=True, exist_ok=True)
        args.tex.write_text(tex_text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
