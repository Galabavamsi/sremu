"""JSON Schema export of the scenario and state-library models (DESIGN.md sections 2.5, 9.1).

``sremu schema scenario`` / ``sremu schema states`` print these schemas (JSON Schema draft
2020-12, generated by pydantic). Copies ship in ``sremu/scenario/schemas/`` for external
tools and for ``docs/scenario_reference.md`` (generated by WP12); a unit test checks that
the shipped copies equal the regenerated schemas.

The schemas check structure, types, enums, ranges and the exact-quantity text syntax. They
cannot express the cross-field rules (exactly one of two fields, strictly increasing
times, ...) or the scenario guards; ``sremu validate`` applies those. They also cannot
reject an integral float such as ``1e6`` for an exact field (JSON Schema treats ``1e6``
and ``1000000`` as the same integer); the loader rejects it (R1).
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Final

from pydantic import BaseModel

from sremu.scenario.models import SCHEMA_VERSION, Scenario, StateLibrary

__all__ = [
    "JSON_SCHEMA_DIALECT",
    "SCHEMA_FILES",
    "export_schema",
    "packaged_schema_dir",
    "scenario_json_schema",
    "schema_text",
    "state_library_json_schema",
    "write_schemas",
]

JSON_SCHEMA_DIALECT: Final[str] = "https://json-schema.org/draft/2020-12/schema"

SCHEMA_FILES: Final[dict[str, str]] = {
    "scenario": "scenario.schema.json",
    "states": "states.schema.json",
}
"""Schema kind -> file name in :func:`packaged_schema_dir`."""


def export_schema(model: type[BaseModel], kind: str, title: str) -> dict[str, Any]:
    """JSON Schema of ``model`` (validation mode) with ``$schema``, ``$id`` and ``title``."""
    body = model.model_json_schema(mode="validation")
    body.pop("title", None)
    return {
        "$schema": JSON_SCHEMA_DIALECT,
        "$id": f"urn:sremu:schema:{kind}:{SCHEMA_VERSION}",
        "title": title,
        **body,
    }


def scenario_json_schema() -> dict[str, Any]:
    """JSON Schema of a scenario file (section 9.2)."""
    return export_schema(Scenario, "scenario", "sremu scenario")


def state_library_json_schema() -> dict[str, Any]:
    """JSON Schema of a state-library file (section 9.4)."""
    return export_schema(StateLibrary, "states", "sremu RIS state library")


def schema_text(schema: dict[str, Any]) -> str:
    """Stable text form (2-space indent, sorted keys, trailing newline)."""
    return json.dumps(schema, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def packaged_schema_dir() -> Path:
    """Directory of the shipped schema copies (``sremu/scenario/schemas``)."""
    return Path(__file__).resolve().parent / "schemas"


def write_schemas(out_dir: str | Path | None = None) -> list[Path]:
    """Write the scenario and state-library schemas; returns the written paths."""
    out = Path(out_dir) if out_dir is not None else packaged_schema_dir()
    out.mkdir(parents=True, exist_ok=True)
    written = []
    for kind, fn in (("scenario", scenario_json_schema), ("states", state_library_json_schema)):
        path = out / SCHEMA_FILES[kind]
        path.write_text(schema_text(fn()), encoding="utf-8", newline="\n")
        written.append(path)
    return written
